#!/usr/bin/env python3
"""
makeCase.py - generate every parameter-dependent file of the case
=================================================================
Wang, Chen & Meng (2013), Appl. Therm. Eng. 54, 237-246
Conjugate heat transfer of cryogenic methane, rectangular cooling channel,
half-width (z >= 0) model, OpenFOAM v2412 (ESI), chtMultiRegionSimpleFoam.

Writes
  system/blockMeshDict              18 blocks, cellZones "fluid" and "solid"
  system/fluid/topoSetDict          face zones at x-planes (bulk T, p, mass flow)
  system/bulkPlanes                 surfaceFieldValue function objects (included by controlDict)
  system/planes.txt                 plane name -> x position
  system/decomposeParDict (+ regions)
  0.orig/fluid/{U,p,p_rgh,T,k,omega,nut,alphat}
  0.orig/solid/T
  constant/solid/thermophysicalProperties
  constant/fluid/thermophysicalProperties   (property tables from CoolProp)

Usage examples
  python3 tools/makeCase.py                          # baseline: H=2mm, U=15 m/s, lambda_s=100
  python3 tools/makeCase.py --lambda-s 20            # Section 3.1, stainless-steel-like fin
  python3 tools/makeCase.py --H 4e-3 --U 10          # Section 3.2, R=2 (constant mass flow)
  python3 tools/makeCase.py --preset coarse          # quick test mesh
"""
import argparse
import math
import sys
from pathlib import Path

CASE = Path(__file__).resolve().parent.parent

# nx must be divisible by 4 (sections 0.25 / 0.5 / 0.25 of the cell count);
# nyf must be even (two-sided grading of the fluid), nyf/nys are y-cells,
# nzf/nzs are z-cells (fluid half width / solid side wall).
# "fine" reproduces the paper's 1000 x 110 x 55 cells.
PRESETS = {
    "coarse": dict(nx=240,  nyf=40, nys=6,  nzf=20, nzs=5,  y1=5e-6),
    "medium": dict(nx=480,  nyf=64, nys=8,  nzf=32, nzs=8,  y1=1e-6),
    "fine":   dict(nx=1000, nyf=90, nys=10, nzf=45, nzs=10, y1=0.25e-6),
}


# --------------------------------------------------------------------------
def parse():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--preset", choices=PRESETS, default="fine")
    for k in ("nx", "nyf", "nys", "nzf", "nzs"):
        ap.add_argument(f"--{k}", type=int, help="override preset")
    ap.add_argument("--y1", type=float, help="first fluid cell height at the wall [m] (target y+<1)")
    ap.add_argument("--H", type=float, default=2e-3, help="channel inner height [m]")
    ap.add_argument("--W", type=float, default=2e-3, help="channel inner width [m]")
    ap.add_argument("--tw", type=float, default=0.5e-3, help="solid wall thickness [m]")
    ap.add_argument("--L", type=float, default=0.6, help="total length [m]")
    ap.add_argument("--x1", type=float, default=0.15, help="start of heated section [m]")
    ap.add_argument("--x2", type=float, default=0.45, help="end of heated section [m]")
    ap.add_argument("--U", type=float, default=15.0, help="inlet velocity [m/s]")
    ap.add_argument("--T0", type=float, default=120.0, help="inlet / initial temperature [K]")
    ap.add_argument("--p", type=float, default=8e6, help="outlet pressure = property table pressure [Pa]")
    ap.add_argument("--q", type=float, default=3e6, help="heat flux on heated top surface [W/m2]")
    ap.add_argument("--lambda-s", dest="lambda_s", type=float, default=100.0,
                    help="solid thermal conductivity [W/m/K]")
    ap.add_argument("--intensity", type=float, default=0.05, help="inlet turbulence intensity")
    ap.add_argument("--mixlen", type=float, default=0.07, help="inlet mixing length / Dh")
    ap.add_argument("--nplanes", type=int, default=6, help="intervals between x1 and x2 for bulk planes")
    ap.add_argument("--np", type=int, default=32, help="number of MPI ranks for decomposeParDict")
    ap.add_argument("--Tmin", type=float, default=100.0)
    ap.add_argument("--Tmax", type=float, default=400.0)
    ap.add_argument("--dT", type=float, default=0.5)
    ap.add_argument("--skip-properties", action="store_true",
                    help="do not (re)generate the CoolProp property tables")
    a = ap.parse_args()
    for k, v in PRESETS[a.preset].items():
        if getattr(a, k, None) is None:
            setattr(a, k, v)
    if a.nx % 4 or a.nyf % 2:
        sys.exit("nx must be divisible by 4 and nyf must be even")
    return a


def hdr(cls, obj, loc):
    return ("/*--------------------------------*- C++ -*----------------------------------*\\\n"
            "  Generated by tools/makeCase.py - edit the script/arguments, not this file.\n"
            "\\*---------------------------------------------------------------------------*/\n"
            "FoamFile\n{\n    version     2.0;\n    format      ascii;\n"
            f"    class       {cls};\n    location    \"{loc}\";\n    object      {obj};\n}}\n"
            "// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //\n\n")


def write(rel, text):
    path = CASE / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"  wrote {rel}")


def g(x):
    return f"{x:.9g}"


def dict_block(name, entries, ind=0):
    pad = " " * ind
    s = f"{pad}{name}\n{pad}{{\n"
    for e in entries:
        s += f"{pad}    {e}\n"
    return s + f"{pad}}}\n"


# --------------------------------------------------------------------------
def growth(L, n, y1):
    """cell-to-cell ratio r such that y1*(1+r+...+r^(n-1)) = L (r>=1)."""
    if y1 * n >= L * (1 - 1e-12):
        print(f"  WARNING: first cell {y1:g} m too large for {n} cells over {L:g} m -> uniform")
        return 1.0
    f = lambda r: y1 * (r ** n - 1.0) / (r - 1.0) - L
    lo, hi = 1.0 + 1e-9, 2.0
    while f(hi) < 0:
        hi *= 1.5
    for _ in range(300):
        mid = 0.5 * (lo + hi)
        if f(mid) > 0:
            hi = mid
        else:
            lo = mid
    return 0.5 * (lo + hi)


# --------------------------------------------------------------------------
def block_mesh(a):
    """18 blocks on a 3 (x) x 3 (y) x 2 (z) lattice.
    x sections : 0-x1 (insulated) | x1-x2 (heated) | x2-L (insulated)
    y rows     : bottom solid | fluid | top solid
    z columns  : fluid half width | solid side wall (symmetry plane at z=0)
    """
    xs = [0.0, a.x1, a.x2, a.L]
    ys = [-a.tw, 0.0, a.H, a.H + a.tw]
    zs = [0.0, a.W / 2, a.W / 2 + a.tw]
    nxs = [a.nx // 4, a.nx // 2, a.nx // 4]
    nys = [a.nys, a.nyf, a.nys]
    nzs = [a.nzf, a.nzs]

    # grading (last-cell / first-cell); same list per row/column/section so
    # that shared block edges are identical
    rs = 4.0                                   # solid: fine towards the interface
    ry_half = growth(a.H / 2, a.nyf // 2, a.y1)
    Ry = ry_half ** (a.nyf // 2 - 1)
    rz = growth(a.W / 2, a.nzf, a.y1)
    Rz = rz ** (a.nzf - 1)
    gx = ["1", "1", "1"]
    gy = [f"{1 / rs:.6g}", f"((0.5 0.5 {Ry:.6g}) (0.5 0.5 {1 / Ry:.6g}))", f"{rs:.6g}"]
    gz = [f"{1 / Rz:.6g}", f"{rs:.6g}"]

    print(f"  cells: {a.nx} x {2 * a.nys + a.nyf} x {a.nzf + a.nzs} "
          f"= {a.nx * (2 * a.nys + a.nyf) * (a.nzf + a.nzs):,}")
    print(f"  wall-normal growth: y {ry_half:.4f}/cell (centre cell {a.y1 * Ry * 1e6:.1f} um), "
          f"z {rz:.4f}/cell (centre cell {a.y1 * Rz * 1e6:.1f} um), dx = {a.L / a.nx * 1e3:.3f} mm")

    vid = lambda i, j, k: i + 4 * j + 16 * k
    verts = [(xs[i], ys[j], zs[k]) for k in range(3) for j in range(4) for i in range(4)]
    assert all(verts[vid(i, j, k)] == (xs[i], ys[j], zs[k])
               for i in range(4) for j in range(4) for k in range(3))

    corners = lambda i, j, k: [vid(i, j, k), vid(i + 1, j, k), vid(i + 1, j + 1, k), vid(i, j + 1, k),
                               vid(i, j, k + 1), vid(i + 1, j, k + 1), vid(i + 1, j + 1, k + 1),
                               vid(i, j + 1, k + 1)]
    # local face lists with outward normals
    FACE = {"xmin": (0, 4, 7, 3), "xmax": (1, 2, 6, 5), "ymin": (0, 1, 5, 4),
            "ymax": (3, 7, 6, 2), "zmin": (0, 3, 2, 1), "zmax": (4, 5, 6, 7)}

    blocks, patches = [], {n: [] for n in ("inlet", "outlet", "topHeated", "solidInsulated",
                                           "symmetryFluid", "symmetrySolid")}
    for i in range(3):
        for j in range(3):
            for k in range(2):
                fluid = (j == 1 and k == 0)
                c = corners(i, j, k)
                blocks.append((("fluid" if fluid else "solid"), c,
                               (nxs[i], nys[j], nzs[k]), (gx[i], gy[j], gz[k])))
                face = lambda nm: tuple(c[v] for v in FACE[nm])
                if i == 0:
                    patches["inlet" if fluid else "solidInsulated"].append(face("xmin"))
                if i == 2:
                    patches["outlet" if fluid else "solidInsulated"].append(face("xmax"))
                if j == 0:
                    patches["solidInsulated"].append(face("ymin"))
                if j == 2:
                    patches["topHeated" if i == 1 else "solidInsulated"].append(face("ymax"))
                if k == 0:
                    patches["symmetryFluid" if fluid else "symmetrySolid"].append(face("zmin"))
                if k == 1:
                    patches["solidInsulated"].append(face("zmax"))

    # every boundary face of the lattice must be in exactly one patch (no defaultFaces)
    expected = 2 * (3 * 2) + 2 * (3 * 2) + 2 * (3 * 3)
    got = sum(len(v) for v in patches.values())
    assert got == expected, (got, expected)
    allf = [tuple(sorted(f)) for v in patches.values() for f in v]
    assert len(set(allf)) == len(allf)

    txt = hdr("dictionary", "blockMeshDict", "system")
    txt += "scale   1;\n\nvertices\n(\n"
    txt += "".join(f"    ({g(x)} {g(y)} {g(z)})\n" for x, y, z in verts)
    txt += ");\n\nblocks\n(\n"
    for zone, c, n, gr in blocks:
        txt += (f"    hex ({' '.join(map(str, c))}) {zone} ({n[0]} {n[1]} {n[2]}) "
                f"simpleGrading ({gr[0]} {gr[1]} {gr[2]})\n")
    txt += ");\n\nedges\n(\n);\n\nboundary\n(\n"
    ptype = {"inlet": "patch", "outlet": "patch", "topHeated": "wall", "solidInsulated": "wall",
             "symmetryFluid": "symmetryPlane", "symmetrySolid": "symmetryPlane"}
    for name, faces in patches.items():
        txt += f"    {name}\n    {{\n        type {ptype[name]};\n        faces\n        (\n"
        txt += "".join(f"            ({' '.join(map(str, f))})\n" for f in faces)
        txt += "        );\n    }\n"
    txt += ");\n\nmergePatchPairs\n(\n);\n"
    write("system/blockMeshDict", txt)


# --------------------------------------------------------------------------
def planes(a):
    """Face zones at x-planes inside the heated section (nearest real cell-face plane)."""
    dx = a.L / a.nx
    xs = []
    for i in range(a.nplanes + 1):
        x = a.x1 + i * (a.x2 - a.x1) / a.nplanes
        xs.append(round(x / dx) * dx)
    hw = 0.05 * dx                         # slab half width << dx/2: only x-normal faces qualify

    t = hdr("dictionary", "topoSetDict", "system/fluid") + "actions\n(\n"
    for i, x in enumerate(xs):
        t += ("    {\n"
              f"        name    plane{i}_faces;\n        type    faceSet;\n        action  new;\n"
              "        source  boxToFace;\n"
              f"        box     ({g(x - hw)} -1 -1) ({g(x + hw)} 1 1);\n    }}\n"
              "    {\n"
              f"        name    plane{i};\n        type    faceZoneSet;\n        action  new;\n"
              f"        source  setToFaceZone;\n        faceSet plane{i}_faces;\n    }}\n")
    t += ");\n"
    write("system/fluid/topoSetDict", t)

    f = ("// Bulk quantities on x-planes of the FLUID region (included by controlDict)\n"
         "// T, h : mass-flux (phi) weighted;  p : area average\n\n")
    common = ["type            surfaceFieldValue;", "libs            (fieldFunctionObjects);",
              "region          fluid;", "writeControl    timeStep;", "writeInterval   200;",
              "writeFields     false;", "log             false;", "regionType      faceZone;"]
    for i in range(len(xs)):
        f += dict_block(f"bulk_plane{i}", common + [f"name            plane{i};",
                        "operation       weightedAverage;", "weightField     phi;",
                        "fields          (T h);"])
        f += dict_block(f"pAvg_plane{i}", common + [f"name            plane{i};",
                        "operation       areaAverage;", "fields          (p);"])
        f += dict_block(f"mdot_plane{i}", common + [f"name            plane{i};",
                        "operation       sum;", "fields          (phi);"])
    write("system/bulkPlanes", f)
    write("system/planes.txt", "plane  x[m]\n" + "".join(f"plane{i}  {x:.6f}\n" for i, x in enumerate(xs)))


# --------------------------------------------------------------------------
def fields(a):
    Dh = 2 * a.H * a.W / (a.H + a.W)
    k0 = 1.5 * (a.U * a.intensity) ** 2
    l = a.mixlen * Dh
    w0 = math.sqrt(k0) / (0.09 ** 0.25 * l)
    print(f"  Dh = {Dh * 1e3:.3f} mm, inlet k = {k0:.4g} m2/s2, omega = {w0:.4g} 1/s "
          f"(I = {a.intensity:.0%}, l = {a.mixlen} Dh)")

    def vf(cls, name, region, dims, internal, bnd):
        s = hdr(cls, name, f"0/{region}")
        s += f"dimensions      {dims};\n\ninternalField   {internal};\n\nboundaryField\n{{\n"
        for patch, entries in bnd.items():
            s += dict_block(patch, entries, 4)
        s += "}\n"
        write(f"0.orig/{region}/{name}", s)

    W = "fluid_to_solid"
    Uv = f"({a.U:g} 0 0)"
    sym = ["type            symmetryPlane;"]
    vf("volVectorField", "U", "fluid", "[0 1 -1 0 0 0 0]", f"uniform {Uv}", {
        "inlet": ["type            fixedValue;", f"value           uniform {Uv};"],
        "outlet": ["type            zeroGradient;"],
        "symmetryFluid": sym,
        W: ["type            noSlip;"]})
    vf("volScalarField", "p_rgh", "fluid", "[1 -1 -2 0 0 0 0]", f"uniform {a.p:g}", {
        "inlet": ["type            fixedFluxPressure;", f"value           uniform {a.p:g};"],
        "outlet": ["type            fixedValue;", f"value           uniform {a.p:g};"],
        "symmetryFluid": sym,
        W: ["type            fixedFluxPressure;", f"value           uniform {a.p:g};"]})
    calc_p = ["type            calculated;", f"value           uniform {a.p:g};"]
    vf("volScalarField", "p", "fluid", "[1 -1 -2 0 0 0 0]", f"uniform {a.p:g}", {
        "inlet": calc_p, "outlet": calc_p, "symmetryFluid": sym, W: calc_p})
    vf("volScalarField", "T", "fluid", "[0 0 0 1 0 0 0]", f"uniform {a.T0:g}", {
        "inlet": ["type            fixedValue;", f"value           uniform {a.T0:g};"],
        "outlet": ["type            zeroGradient;"],
        "symmetryFluid": sym,
        W: ["type            compressible::turbulentTemperatureCoupledBaffleMixed;",
            "Tnbr            T;", "kappaMethod     fluidThermo;", f"value           uniform {a.T0:g};"]})
    vf("volScalarField", "k", "fluid", "[0 2 -2 0 0 0 0]", f"uniform {k0:.6g}", {
        "inlet": ["type            fixedValue;", f"value           uniform {k0:.6g};"],
        "outlet": ["type            zeroGradient;"],
        "symmetryFluid": sym,
        W: ["type            kLowReWallFunction;", f"value           uniform {k0:.6g};"]})
    vf("volScalarField", "omega", "fluid", "[0 0 -1 0 0 0 0]", f"uniform {w0:.6g}", {
        "inlet": ["type            fixedValue;", f"value           uniform {w0:.6g};"],
        "outlet": ["type            zeroGradient;"],
        "symmetryFluid": sym,
        W: ["type            omegaWallFunction;", f"value           uniform {w0:.6g};"]})
    z = ["type            calculated;", "value           uniform 0;"]
    vf("volScalarField", "nut", "fluid", "[0 2 -1 0 0 0 0]", "uniform 0", {
        "inlet": z, "outlet": z, "symmetryFluid": sym,
        W: ["type            nutUSpaldingWallFunction;", "value           uniform 0;"]})
    vf("volScalarField", "alphat", "fluid", "[1 -1 -1 0 0 0 0]", "uniform 0", {
        "inlet": z, "outlet": z, "symmetryFluid": sym,
        W: ["type            compressible::alphatWallFunction;", "Prt             0.85;",
            "value           uniform 0;"]})
    vf("volScalarField", "T", "solid", "[0 0 0 1 0 0 0]", f"uniform {a.T0:g}", {
        "topHeated": ["type            externalWallHeatFluxTemperature;",
                      "mode            flux;",
                      f"q               uniform {a.q:g};      // W/m2, positive = heat INTO the solid",
                      "kappaMethod     solidThermo;", f"value           uniform {a.T0:g};"],
        "solidInsulated": ["type            zeroGradient;"],
        "symmetrySolid": sym,
        "solid_to_fluid": ["type            compressible::turbulentTemperatureCoupledBaffleMixed;",
                           "Tnbr            T;", "kappaMethod     solidThermo;",
                           f"value           uniform {a.T0:g};"]})
    return Dh


# --------------------------------------------------------------------------
def solid_thermo(a):
    s = hdr("dictionary", "thermophysicalProperties", "constant/solid")
    s += ("thermoType\n{\n    type            heSolidThermo;\n    mixture         pureMixture;\n"
          "    transport       constIso;\n    thermo          hConst;\n"
          "    equationOfState rhoConst;\n    specie          specie;\n    energy          sensibleEnthalpy;\n}\n\n"
          "// Steady state: only kappa matters (rho and Cp are placeholders)\n"
          "mixture\n{\n    specie\n    {\n        molWeight   50;\n    }\n"
          "    transport\n    {\n" f"        kappa       {a.lambda_s:g};\n    }}\n"
          "    thermodynamics\n    {\n        Hf          0;\n        Cp          500;\n    }\n"
          "    equationOfState\n    {\n        rho         8000;\n    }\n}\n")
    write("constant/solid/thermophysicalProperties", s)


def decompose(a):
    for reg in ("", "fluid/", "solid/"):
        s = hdr("dictionary", "decomposeParDict", "system/" + reg.rstrip("/"))
        s += (f"numberOfSubdomains {a.np};\nmethod          scotch;\n")
        write(f"system/{reg}decomposeParDict", s)


# --------------------------------------------------------------------------
def fluid_thermo(a, Dh):
    try:
        from CoolProp.CoolProp import PropsSI
    except ImportError:
        sys.exit("CoolProp not found: pip install CoolProp   (or use --skip-properties)")
    fl = "Methane"
    n = int(round((a.Tmax - a.Tmin) / a.dT)) + 1
    T = [a.Tmin + i * a.dT for i in range(n)]
    rho, cp, mu, kap, h = [], [], [], [], []
    for t in T:
        rho.append(PropsSI("D", "T", t, "P", a.p, fl))
        cp.append(PropsSI("C", "T", t, "P", a.p, fl))
        mu.append(PropsSI("V", "T", t, "P", a.p, fl))
        kap.append(PropsSI("L", "T", t, "P", a.p, fl))
        h.append(PropsSI("H", "T", t, "P", a.p, fl))
    h0 = PropsSI("H", "T", a.T0, "P", a.p, fl)
    hs = [x - h0 for x in h]                     # Hs(T0) = 0

    imax = max(range(n), key=lambda i: cp[i])
    iin = min(range(n), key=lambda i: abs(T[i] - a.T0))
    Re = rho[iin] * a.U * Dh / mu[iin]
    print(f"  CoolProp {fl} at p = {a.p / 1e6:g} MPa:")
    print(f"    pseudo-critical T (max Cp on grid) = {T[imax]:.1f} K, Cp,max = {cp[imax]:.0f} J/kg/K")
    print(f"    inlet: rho = {rho[iin]:.1f} kg/m3, mu = {mu[iin]:.3e} Pa s, Re = {Re:.4g}, "
          f"mdot(full channel) = {rho[iin] * a.U * a.H * a.W * 1e3:.4f} g/s")
    print(f"    paper Table 1 gives Re = 1.551e5 for U = 20 m/s, Dh = 2 mm -> expect ~{1.551e5 * a.U / 20 * Dh / 2e-3:.3e} "
          f"here if the property sets agree (CoolProp vs SRK differ by a few %)")

    def table(vals):
        return "\n".join(f"            ({T[i]:g} {vals[i]:.8g})" for i in range(n))

    s = hdr("dictionary", "thermophysicalProperties", "constant/fluid")
    s += (f"// Methane at p = {a.p:g} Pa from CoolProp, T {a.Tmin:g}-{a.Tmax:g} K, step {a.dT:g} K.\n"
          "// Properties are functions of T only (pressure drop of the channel is ~2 % of p).\n\n"
          "thermoType\n{\n    type            heRhoThermo;\n    mixture         pureMixture;\n"
          "    transport       tabulated;\n    thermo          hTabulated;\n"
          "    equationOfState icoTabulated;\n    specie          specie;\n"
          "    energy          sensibleEnthalpy;\n}\n\n"
          "mixture\n{\n    specie\n    {\n        molWeight   16.043;\n    }\n\n"
          "    equationOfState\n    {\n        rho\n        (\n" + table(rho) + "\n        );\n    }\n\n"
          "    thermodynamics\n    {\n        Hf          0;\n        Sf          0;\n"
          "        Cp\n        (\n" + table(cp) + "\n        );\n"
          "        Hs\n        (\n" + table(hs) + "\n        );\n    }\n\n"
          "    transport\n    {\n        mu\n        (\n" + table(mu) + "\n        );\n"
          "        kappa\n        (\n" + table(kap) + "\n        );\n    }\n}\n")
    write("constant/fluid/thermophysicalProperties", s)


# --------------------------------------------------------------------------
def main():
    a = parse()
    print("Case parameters:")
    print(f"  H = {a.H * 1e3:g} mm, W = {a.W * 1e3:g} mm (R = {a.H / a.W:g}), wall = {a.tw * 1e3:g} mm, "
          f"U = {a.U:g} m/s, q = {a.q:g} W/m2, lambda_s = {a.lambda_s:g} W/m/K, p = {a.p:g} Pa")
    print(f"  heated length {a.x2 - a.x1:g} m -> expected power (half model) "
          f"= {a.q * (a.x2 - a.x1) * (a.W / 2 + a.tw):.1f} W")
    block_mesh(a)
    planes(a)
    Dh = fields(a)
    solid_thermo(a)
    decompose(a)
    if not a.skip_properties:
        fluid_thermo(a, Dh)
    print("done.")


if __name__ == "__main__":
    main()
